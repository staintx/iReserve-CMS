/**
 * Returns a high-resolution food photo URL for a menu item
 */
export const resolveDishImage = (dish) => {
  if (dish?.image_url && dish.image_url.trim() !== "") {
    return dish.image_url;
  }
  const name = String(dish?.name || "").toLowerCase().trim();
  for (const [key, url] of Object.entries(DISH_IMAGE_REGISTRY)) {
    if (name.includes(key)) {
      return url;
    }
  }
  const category = dish?.category || "default";
  return CATEGORY_FALLBACK_IMAGES[category] || CATEGORY_FALLBACK_IMAGES.default;
};

/**
 * Resolves 3 dish preview photos for a package card (Baemin Reference 2)
 */
export const resolvePackagePreviewDishes = (pkg) => {
  const pkgDishes = [];
  if (Array.isArray(pkg?.menu_items) && pkg.menu_items.length > 0) {
    pkg.menu_items.forEach((item) => {
      const name = typeof item === "string" ? item : item?.name;
      if (name) {
        pkgDishes.push({
          name,
          image: resolveDishImage(typeof item === "object" ? item : { name }),
        });
      }
    });
  }

  const defaultPreviews = [
    {
      name: "Lechon Pork Belly",
      image: "https://images.unsplash.com/photo-1529193591184-b1d58069ecdd?auto=format&fit=crop&w=600&q=80",
    },
    {
      name: "Chicken Cordon Bleu",
      image: "https://images.unsplash.com/photo-1604908176997-125f25cc6f3d?auto=format&fit=crop&w=600&q=80",
    },
    {
      name: "Pancit Sotanghon",
      image: "https://images.unsplash.com/photo-1585032226651-759b368d7246?auto=format&fit=crop&w=600&q=80",
    },
  ];

  if (pkgDishes.length >= 3) {
    return pkgDishes.slice(0, 3);
  }
  return [...pkgDishes, ...defaultPreviews].slice(0, 3);
};

